    /// Dispatching: telegram addressed to slave #4 is answered by that slave only.
    #[test]
    fn dispatch_multiple_slaves() {
        let mut req = [0u8; 128];
        let mut out = [0u8; MAX_REPLY_LEN];

        let mut pi_i3 = [0u8; 1];
        let mut pi_q3 = [0u8; 1];
        let slave3 = DpSlave::new(
            SlaveConfig {
                address: 3,
                ..slave_config()
            },
            &mut pi_i3[..],
            &mut pi_q3[..],
        );
        let mut pi_i4 = [0u8; 1];
        let mut pi_q4 = [0u8; 1];
        let slave4 = DpSlave::new(
            SlaveConfig {
                address: 4,
                ..slave_config()
            },
            &mut pi_i4[..],
            &mut pi_q4[..],
        );
        let mut slaves = [slave3, slave4];

        // Broadcast: everyone must see it, nobody replies.
        let t = make_request(
            &mut req,
            127,
            crate::consts::SAP_SLAVE_GLOBAL_CONTROL,
            crate::consts::SAP_MASTER_MS0,
            FunctionCode::Request {
                fcb: FrameCountBit::Inactive,
                req: RequestType::SdnLow,
            },
            &[0x02, 0x00],
        );
        assert_eq!(dispatch(&mut slaves, now(), &t, &mut out), 0);

        // Unicast FDL status to slave #4: answered with sa = 4.
        let length = TelegramTx::new(&mut req)
            .send_fdl_status_request(4, MASTER)
            .bytes_sent();
        let t = Telegram::deserialize(&req[..length]).unwrap().unwrap().0;
        let reply = dispatch(&mut slaves, now(), &t, &mut out);
        let Telegram::Data(dt) = parse_reply(reply, &out) else {
            panic!("expected a data telegram")
        };
        assert_eq!(dt.h.sa, 4);

        // Unicast to an address which is not on the bus: silence.
        let length = TelegramTx::new(&mut req)
            .send_fdl_status_request(7, MASTER)
            .bytes_sent();
        let t = Telegram::deserialize(&req[..length]).unwrap().unwrap().0;
        assert_eq!(dispatch(&mut slaves, now(), &t, &mut out), 0);
    }

    /// Helper for checking the PDU of a parsed data telegram reply.
    trait TelegramPdu {
        fn pdu_bytes(&self) -> &[u8];
    }

    impl TelegramPdu for Telegram<'_> {
        fn pdu_bytes(&self) -> &[u8] {
            match self {
                Telegram::Data(t) => t.pdu,
                _ => panic!("expected a data telegram"),
            }
        }
    }
