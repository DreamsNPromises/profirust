    fn a12_watchdog() {
        let mut slave = make_slave();
        bring_to_dxchg(&mut slave, now(), FrameCountBit::High);
        slave.pi_q_mut()[0] = 0x55;

        // WD factors (1, 10) -> 100 ms watchdog period.
        // Not yet expired at 100 ms + 1 µs... actually > period, so expired:
        let mut time = now() + crate::time::Duration::from_millis(100);
        slave.tick(time);
        assert_eq!(slave.state(), SlaveState::Dxchg); // exactly 100 ms: not > period

        time = time + crate::time::Duration::from_micros(2);
        slave.tick(time);
        assert_eq!(slave.state(), SlaveState::Wprm);
        assert_eq!(slave.pi_q(), &[0x00]); // fail_safe: pi_q cleared
        assert!(slave.prm_req);
        assert!(slave.diag_pending);

        // Recovery: re-parameterization brings the slave back into data exchange.
        bring_to_dxchg(&mut slave, time, FrameCountBit::Low);
        assert_eq!(slave.state(), SlaveState::Dxchg);
    }

